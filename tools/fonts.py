"""Web fonts for tractoaretecuci.ro: subset to the characters the site uses (Romanian ș ț ă â î included)
and print metric overrides for an Arial fallback, so text does not move when the web font arrives.

Sources (SIL OFL 1.1, from github.com/google/fonts): Inter variable, Barlow Semi Condensed 600/700,
downloaded to .tmp/fonts. Usage: python tools/fonts.py   (writes assets/fonts/*.woff2 and src/css/fonts.css)
"""
import hashlib, io, os, sys
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer
from fontTools import subset

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, '.tmp', 'fonts')
OUT = os.path.join(ROOT, 'assets', 'fonts')
os.makedirs(OUT, exist_ok=True)

UNICODES = ('U+0020-007E,U+00A0-00FF,U+0102-0103,U+0218-021B,U+2013-2014,U+2018-201E,'
            'U+2022,U+2026,U+20AC,U+2122,U+2192,U+2212,U+00D7')
SAMPLE = ('Tractoare și utilaje agricole second hand din import, verificate și livrate în toată țara. '
          'Fendt 820 Vario TMS, an de fabricație 2011, 7.500 ore de funcționare. Sună acum sau scrie pe WhatsApp.')
ARIAL = {400: r'C:\Windows\Fonts\arial.ttf', 700: r'C:\Windows\Fonts\arialbd.ttf'}


def width(font, text):
    cmap = font.getBestCmap()
    hmtx = font['hmtx']
    return sum(hmtx[cmap[ord(c)]][0] for c in text if ord(c) in cmap) / font['head'].unitsPerEm


def build(src_path, name, weight_range=None, pin=None):
    font = TTFont(src_path)
    if 'fvar' in font:
        limits = dict(pin or {})
        if weight_range:
            limits['wght'] = weight_range
        font = instancer.instantiateVariableFont(font, limits)
        # Round-trip through bytes: subsetting an in-memory instance trips over lazily loaded gvar data.
        buf = io.BytesIO()
        font.save(buf)
        buf.seek(0)
        font = TTFont(buf, lazy=False)
    opts = subset.Options()
    opts.flavor = 'woff2'
    opts.layout_features = ['kern', 'liga', 'calt', 'tnum', 'case', 'ccmp', 'locl', 'mark', 'mkmk']
    opts.name_IDs = ['*']
    opts.notdef_outline = True
    opts.hinting = False
    sub = subset.Subsetter(opts)
    sub.populate(unicodes=subset.parse_unicodes(UNICODES))
    sub.subset(font)
    tmp = os.path.join(OUT, f'{name}.tmp.woff2')
    font.flavor = 'woff2'
    font.save(tmp)
    digest = hashlib.sha1(open(tmp, 'rb').read()).hexdigest()[:8]
    final = os.path.join(OUT, f'{name}.{digest}.woff2')
    for f in os.listdir(OUT):
        if f.startswith(name + '.') and f.endswith('.woff2') and '.tmp.' not in f and os.path.join(OUT, f) != final:
            os.remove(os.path.join(OUT, f))
    os.replace(tmp, final) if not os.path.exists(final) else os.remove(tmp)
    return os.path.basename(final), font


def fallback(web, arial_weight):
    arial = TTFont(ARIAL[arial_weight])
    size_adjust = width(web, SAMPLE) / width(arial, SAMPLE)
    upm = web['head'].unitsPerEm
    hhea = web['hhea']
    return {
        'size-adjust': f'{size_adjust * 100:.2f}%',
        'ascent-override': f'{hhea.ascent / upm / size_adjust * 100:.2f}%',
        'descent-override': f'{abs(hhea.descent) / upm / size_adjust * 100:.2f}%',
        'line-gap-override': f'{hhea.lineGap / upm / size_adjust * 100:.2f}%',
    }


inter_file, inter = build(os.path.join(SRC, 'Inter-VF.ttf'), 'inter-var', weight_range=(400, 700), pin={'opsz': 14})
b600_file, b600 = build(os.path.join(SRC, 'BSC-600.ttf'), 'barlow-sc-600')
b700_file, b700 = build(os.path.join(SRC, 'BSC-700.ttf'), 'barlow-sc-700')

inter_regular = instancer.instantiateVariableFont(TTFont(os.path.join(SRC, 'Inter-VF.ttf')), {'opsz': 14, 'wght': 400})
inter_bold = instancer.instantiateVariableFont(TTFont(os.path.join(SRC, 'Inter-VF.ttf')), {'opsz': 14, 'wght': 700})


def face(family, src, weight, extra=''):
    return (f"@font-face{{font-family:'{family}';src:url('/assets/fonts/{src}') format('woff2');"
            f"font-weight:{weight};font-style:normal;font-display:swap;{extra}}}\n")


def fb_face(family, local, metrics, weight):
    props = ''.join(f'{k}:{v};' for k, v in metrics.items())
    return f"@font-face{{font-family:'{family}';src:local('{local}');font-weight:{weight};{props}}}\n"


css = ('/* Generated by tools/fonts.py. Inter and Barlow Semi Condensed, SIL OFL 1.1. */\n'
       + face('Inter', inter_file, '400 700')
       + face('Barlow Semi Condensed', b600_file, 600)
       + face('Barlow Semi Condensed', b700_file, 700)
       # One fallback face per weight range, metric-matched on the site's own text (no shift on swap).
       + fb_face('Inter Fallback', 'Arial', fallback(inter_regular, 400), '400 599')
       + fb_face('Inter Fallback', 'Arial Bold', fallback(inter_bold, 700), '600 900')
       + fb_face('Barlow Fallback', 'Arial', fallback(b600, 400), '400 650')
       + fb_face('Barlow Fallback', 'Arial Bold', fallback(b700, 700), '651 900'))
open(os.path.join(ROOT, 'src', 'css', 'fonts.css'), 'w', encoding='utf-8').write(css)
for f in (inter_file, b600_file, b700_file):
    print(f, os.path.getsize(os.path.join(OUT, f)), 'bytes')
print(css)
